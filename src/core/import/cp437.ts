/**
 * Кодовая страница CP437 — в ней нарисованы шрифты REXPaint и почти всех консольных рогаликов.
 * Коды 1–31 здесь не управляющие, а графические: так их рисует экран IBM PC и так их ждут арты.
 */
const LOW = '\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼';
const ASCII = Array.from({ length: 95 }, (_, i) => String.fromCharCode(0x20 + i)).join('');
const HIGH =
  '⌂' +
  'ÇüéâäàåçêëèïîìÄÅ' +
  'ÉæÆôöòûùÿÖÜ¢£¥₧ƒ' +
  'áíóúñÑªº¿⌐¬½¼¡«»' +
  '░▒▓│┤╡╢╖╕╣║╗╝╜╛┐' +
  '└┴┬├─┼╞╟╚╔╩╦╠═╬╧' +
  '╨╤╥╙╘╒╓╫╪┘┌█▄▌▐▀' +
  'αßΓπΣσµτΦΘΩδ∞φε∩' +
  '≡±≥≤⌠⌡÷≈°∙·√ⁿ²■\u00a0';

/** Таблица целиком, 256 символов по коду. */
export const CP437: readonly string[] = [...(LOW + ASCII + HIGH)];

/**
 * Символ ячейки по коду CP437. Пустота, пробел и неразрывный пробел — это «нет символа»: в
 * документе такая ячейка несёт только фон. Коды вне таблицы бывают у расширенных шрифтов
 * REXPaint; их форма неизвестна, поэтому они становятся знаком вопроса, а не молча пропадают.
 */
export function cp437Glyph(code: number): string {
  if (code === 0 || code === 0x20 || code === 0xff) return '';
  return CP437[code] ?? '?';
}
